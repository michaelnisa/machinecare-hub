export const DEFAULT_USD_TO_TZS_RATE = 2600;
export const DEFAULT_USD_TO_ZMW_RATE = 27.5;
export const DEFAULT_USD_TO_BWP_RATE = 13.8;
export const DEFAULT_USD_TO_ZAR_RATE = 18.5;

export function convertUsdToTzs(usd: number, rate = DEFAULT_USD_TO_TZS_RATE): number {
  return Math.round(usd * rate);
}

export function convertTzsToUsd(tzs: number, rate = DEFAULT_USD_TO_TZS_RATE): number {
  return Number((tzs / rate).toFixed(2));
}

export function convertUsdToLocal(
  usd: number,
  currencyCode: string,
  customRates?: Record<string, number>
): number {
  const code = (currencyCode || "USD").toUpperCase();
  if (code === "USD") return usd;
  const rate = customRates?.[code] || REGIONAL_CURRENCIES[code]?.defaultRateToUsd || 1;
  const converted = usd * rate;
  return ["TZS", "UGX", "RWF", "CDF"].includes(code)
    ? Math.round(converted)
    : Number(converted.toFixed(2));
}

export function formatCorridorAmount(
  amount: number,
  currencyCode: string = "USD"
): string {
  const code = (currencyCode || "USD").toUpperCase();
  const cfg = REGIONAL_CURRENCIES[code];
  const symbol = cfg?.symbol || code;
  const isZeroDecimals = ["TZS", "UGX", "RWF", "CDF"].includes(code);

  return `${symbol} ${amount.toLocaleString(undefined, {
    minimumFractionDigits: isZeroDecimals ? 0 : 2,
    maximumFractionDigits: isZeroDecimals ? 0 : 2,
  })}`;
}

export function formatDualCurrency(
  amountUsd: number,
  rate = DEFAULT_USD_TO_TZS_RATE,
  primaryCurrency: "USD" | "TZS" = "USD"
): string {
  const amountTzs = convertUsdToTzs(amountUsd, rate);
  if (primaryCurrency === "USD") {
    return `$${amountUsd.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} (≈ ${amountTzs.toLocaleString()} TZS)`;
  }
  return `${amountTzs.toLocaleString()} TZS (≈ $${amountUsd.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })})`;
}

export function formatTripCurrency(
  amount: number,
  currency: string = "TZS",
  rate = DEFAULT_USD_TO_TZS_RATE
) {
  const curr = (currency || "TZS").toUpperCase();
  if (curr === "USD") {
    const tzs = Math.round(amount * rate);
    return {
      primary: `$${amount.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
      secondary: `≈ ${tzs.toLocaleString()} TZS`,
      full: `$${amount.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} (≈ ${tzs.toLocaleString()} TZS)`,
    };
  } else {
    const usd = Number((amount / rate).toFixed(2));
    return {
      primary: `${Math.round(amount).toLocaleString()} TZS`,
      secondary: `≈ $${usd.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
      full: `${Math.round(amount).toLocaleString()} TZS (≈ $${usd.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })})`,
    };
  }
}

